#!/usr/bin/env python3
"""Host check of the gen8 (A8XX) NativeAdreno submission, interrupt and timer offsets against the pinned msm-next driver.

a6xx_set_pagetable, a7xx_submit (A8XX branches) and a8xx_irq are compiled unchanged as a software oracle in
build/erhai-gpu-oracle (generated, never committed); ring writes and register accesses record into a log.
package/ErhaiGpuSubmitTests.cpp runs NativeAdrenoRing's framed submission with a context entry, NativeAdrenoIrq and
NativeAdrenoTimer built with NATIVE_ADRENO_GEN8 and compares:
- every register the two command streams name (TYPE4 writes and CP_WAIT_REG_MEM polls), in order;
- the submission tail from the CP_SCRATCH_GLOBAL(2) write to the end, word for word;
- the interrupt acknowledgement's register accesses;
- the always-on counter and the interrupt mask.
The ring's deliberate departures (no CP_SMMU_TABLE_UPDATE for its single context, no per-submission statistics
CP_REG_TO_MEM, its cache flush) are outside those comparisons by construction. Software peers only."""
