#!/usr/bin/env python3
"""Zero definitions for the Adreno 740 symbols the sheng display and boot-progress archives reference on erhai.

The sheng package links its GPU probes (GpuPowerProbe, BootLog's GPU rows) into the display bundle and declares the
Adreno driver's statistics weak_import, but the static kernel link still needs a definition. erhai builds without
NativeAdreno (CONFIG_XNU_NATIVE_ADRENO=n: no Adreno 830 support, and sheng's GMU inputs are not reproducible here), so
each symbol that no archive defines gets a stand-in: a zero-filled data block when it is only addressed, a function
that returns 0 when it is called (BRANCH26 relocation). The GPU probes only run with sheng-gpu-* boot arguments, which
erhai does not pass; BootLog reads the zero statistics as "no GPU". The list is derived at build time, so it follows the
sheng package without maintenance. Link it with CONFIG_XNU_EXTRA_LD_ARCHIVES.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/erhai-adreno-stubs'
OUT.mkdir(parents=True, exist_ok=True)
CONSUMERS = [ROOT / 'build/native-legacy-display/libNativeLegacyDisplay.late.a', ROOT / 'build/boot-progress/libBootProgress.a']
NAMES = re.compile(r'native_adreno_|NativeAdreno|ShengGmu|AdrenoHfi|AdrenoPM4')   # C names and mangled C++ members
DATA_BYTES = 0x2000            # larger than every statistics array BootLog indexes


def nm(archive, *flags):
    text = subprocess.run(['xcrun', 'llvm-nm', '-g', '-j', *flags, archive], capture_output=True, text=True, check=True).stdout
    return {line.strip() for line in text.splitlines() if line.strip() and not line.endswith(':')}


for archive in CONSUMERS:
    if not archive.is_file():
        sys.exit(f'{archive} missing: run this after build-native-legacy-display.py and build-boot-progress.py')
wanted = set().union(*(nm(a, '-u') for a in CONSUMERS))
defined = set().union(*(nm(a, '--defined-only') for a in ROOT.glob('build/**/*.a') if OUT not in a.parents))
missing = sorted(s for s in wanted - defined if NAMES.search(s))

called = set()
for archive in CONSUMERS:
    relocations = subprocess.run(['xcrun', 'llvm-objdump', '--macho', '-r', archive], capture_output=True, text=True,
                                 check=True).stdout
    called |= {line.split()[-1] for line in relocations.splitlines() if ' BR26 ' in f' {line} ' or 'BRANCH26' in line}

lines = ['// Generated by scripts/build-erhai-adreno-stubs.py; see its docstring.']
for symbol in missing:
    if symbol in called:
        lines += ['.section __TEXT,__text,regular,pure_instructions', '.p2align 2', f'.globl "{symbol}"', f'"{symbol}":',
                  'mov x0, #0', 'ret']
    else:
        lines += ['.section __DATA,__data', '.p2align 4', f'.globl "{symbol}"', f'"{symbol}":', f'.space {DATA_BYTES}']
(OUT / 'stubs.S').write_text('\n'.join(lines) + '\n')
subprocess.run(['xcrun', '-sdk', 'iphoneos', 'clang', '-target', 'arm64-apple-ios17.0', '-c', OUT / 'stubs.S', '-o',
                OUT / 'stubs.o'], check=True)
archive = OUT / 'libErhaiAdrenoStubs.a'
archive.unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', archive, OUT / 'stubs.o'], check=True)
functions = sum(s in called for s in missing)
print(f'erhai Adreno stand-ins: {len(missing)} symbols ({functions} functions, {len(missing) - functions} data) -> {archive}')
