#!/usr/bin/env python3
"""Host check of package/ErhaiGpuZap.c against the pinned msm-next mdt_loader.c and zap_shader_load_mdt.

The mdt_loader.c functions are compiled unchanged as a software oracle in build/erhai-gpu-oracle (generated, never
committed); the PAS calls record into a log. package/ErhaiGpuZapTests.c loads the pinned local gen80000_zap.mbn and
variants of it through both and compares results, PAS calls, the metadata buffer and the region bytes. The firmware is OEM
and stays in ignored storage. Software peers only; the tablet run is the evidence."""
import hashlib, importlib.util, json, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('prepare_erhai_gpu', ROOT / 'scripts/prepare-erhai-gpu.py')
prepare = importlib.util.module_from_spec(spec); spec.loader.exec_module(prepare)
OUT = ROOT / 'build/erhai-gpu-oracle'
inputs = json.loads((ROOT / 'scripts/data/erhai-gpu-inputs.json').read_text())
for name, pin in inputs['files'].items():
    if name.startswith('msm-next/') and hashlib.sha256((ROOT / '.cache/erhai-gpu-source' / name).read_bytes()).hexdigest() != pin['sha256']:
        raise SystemExit('Pinned erhai input differs: ' + name)
zap = ROOT / '.cache/firmware/erhai-gpu/qcom/gen80000_zap.mbn'
pin = inputs['firmware']['qcom/gen80000_zap.mbn']
if not zap.is_file() or hashlib.sha256(zap.read_bytes()).hexdigest() != pin['sha256']:
    raise SystemExit('Missing or different local qcom/gen80000_zap.mbn (see the _comment of erhai-gpu-inputs.json)')


def function(source, signature):
    at = source.index('{', source.index(signature)) + 1; depth = 1
    while depth:
        depth += {'{': 1, '}': -1}.get(source[at], 0); at += 1
    return source[source.index(signature):at]


mdt = (prepare.MN / 'drivers/soc/qcom/mdt_loader.c').read_text()
mdt_h = (prepare.MN / 'include/linux/soc/qcom/mdt_loader.h').read_text()
adreno = (prepare.MN / 'drivers/gpu/drm/msm/adreno/adreno_gpu.c').read_text()
loader = function(adreno, 'static int zap_shader_load_mdt(')
# The part of zap_shader_load_mdt after the firmware request, which the oracle driver below restates.
for line in ('mem_size = qcom_mdt_get_size(fw);', 'if (mem_size > resource_size(&r)) {', 'ret = -E2BIG;',
             'mem_region = memremap(mem_phys, mem_size,  MEMREMAP_WC);', 'mem_region, mem_phys, mem_size, NULL);',
             'ret = qcom_pas_auth_and_reset(pasid);'):
    if line not in loader: raise SystemExit('zap_shader_load_mdt changed: ' + line)
defines = '\n'.join(re.search(r'^#define ' + n + r'\b.*$', mdt_h, re.M).group(0)
                    for n in ('QCOM_MDT_TYPE_MASK', 'QCOM_MDT_TYPE_HASH', 'QCOM_MDT_RELOCATABLE'))
functions = ['static bool mdt_header_valid(', 'static bool mdt_phdr_loadable(', 'ssize_t qcom_mdt_get_size(',
             'void *qcom_mdt_read_metadata(', 'static int __qcom_mdt_pas_init(', 'static bool qcom_mdt_bins_are_split(',
             'int qcom_mdt_load_no_init(', 'int qcom_mdt_load(']
nl = '\n'
oracle = f'''/* Generated by scripts/check-erhai-gpu-zap.py from pinned Linux sources (GPL-2.0); host test only, never shipped. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <sys/types.h>
typedef uint8_t u8;typedef uint16_t u16;typedef uint32_t u32;typedef uint64_t u64;typedef u64 phys_addr_t;
#define PHYS_ADDR_MAX UINT64_MAX
#define BIT(n) (1u<<(n))
#define SZ_4K 0x1000u
#define ALIGN(x,a) (((x)+((__typeof__(x))(a)-1))&~((__typeof__(x))(a)-1))
#define EINVAL 22
#define ENOMEM 12
#define ENOENT 2
#define E2BIG 7
#define GFP_KERNEL 0
#define kmalloc(n,f) malloc(n)
#define kfree free
#define ERR_PTR(e) ((void *)(intptr_t)(e))
#define PTR_ERR(p) ((long)(intptr_t)(p))
#define IS_ERR(p) ((uintptr_t)(p) >= (uintptr_t)-4095)
#define dev_err(...) ((void)0)
static inline size_t size_add(size_t a,size_t b) {{size_t r;return __builtin_add_overflow(a,b,&r)?SIZE_MAX:r;}}
static inline size_t size_mul(size_t a,size_t b) {{size_t r;return __builtin_mul_overflow(a,b,&r)?SIZE_MAX:r;}}
#define ELFMAG "\\177ELF"
#define SELFMAG 4
#define PT_LOAD 1
struct elf32_hdr {{unsigned char e_ident[16];u16 e_type,e_machine;u32 e_version,e_entry,e_phoff,e_shoff,e_flags;
    u16 e_ehsize,e_phentsize,e_phnum,e_shentsize,e_shnum,e_shstrndx;}};
struct elf32_phdr {{u32 p_type,p_offset,p_vaddr,p_paddr,p_filesz,p_memsz,p_flags,p_align;}};
struct elf32_shdr {{u32 sh_name,sh_type,sh_flags,sh_addr,sh_offset,sh_size,sh_link,sh_info,sh_addralign,sh_entsize;}};
struct firmware {{size_t size;const u8 *data;}};
struct device {{int unused;}};
struct qcom_pas_context;
{defines}
/* The platform: split segments have no file system to come from; PAS calls go to the harness. */
static ssize_t mdt_load_split_segment(void *ptr,const struct elf32_phdr *phdrs,unsigned int segment,const char *fw_name,struct device *dev)
{{(void)ptr;(void)phdrs;(void)segment;(void)fw_name;(void)dev;return -ENOENT;}}
long oracle_pas(u32 cmd,const u64 *args,unsigned count,const void *metadata,size_t metadata_len);
static int qcom_pas_init_image(int pas_id,const void *metadata,size_t size,struct qcom_pas_context *ctx)
{{(void)ctx;u64 a[2]={{(u64)pas_id,0}};return (int)oracle_pas(1,a,2,metadata,size);}}
static int qcom_pas_mem_setup(int pas_id,phys_addr_t addr,phys_addr_t size) {{u64 a[3]={{(u64)pas_id,addr,size}};return (int)oracle_pas(2,a,3,0,0);}}
static int qcom_pas_auth_and_reset(int pas_id) {{u64 a[1]={{(u64)pas_id}};return (int)oracle_pas(5,a,1,0,0);}}
{nl.join(function(mdt, f) for f in functions)}
/* zap_shader_load_mdt after request_firmware: size, region check, qcom_mdt_load into the region, auth_and_reset. */
long oracle_zap(const u8 *data,size_t size,int pasid,void *region,phys_addr_t mem_phys,size_t region_size)
{{
    struct firmware fw={{size,data}};struct device dev;
    ssize_t mem_size=qcom_mdt_get_size(&fw);
    if (mem_size<0) return mem_size;
    if ((size_t)mem_size>region_size) return -E2BIG;
    int ret=qcom_mdt_load(&dev,&fw,"qcom/gen80000_zap.mbn",pasid,region,mem_phys,mem_size,NULL);
    if (ret) return ret;
    return qcom_pas_auth_and_reset(pasid);
}}
'''
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'zap-oracle.c').write_text(oracle)
PKG = ROOT / 'kits/sheng'
san = ['-O1', '-g', '-fsanitize=address,undefined', '-fno-sanitize-recover=all']
run = lambda cmd: subprocess.run(cmd, check=True, timeout=300)
test = OUT / 'test-erhai-gpu-zap'
run(['xcrun', 'clang', '-std=gnu11', *san, '-w', '-c', str(OUT / 'zap-oracle.c'), '-o', str(OUT / 'zap-oracle.o')])
run(['xcrun', 'clang', '-std=gnu11', *san, '-Wall', '-Wextra', '-Werror', '-I', str(PKG), str(PKG / 'ErhaiGpuZapTests.c'),
     str(PKG / 'ErhaiGpuZap.c'), str(OUT / 'zap-oracle.o'), '-o', str(test)])
run([str(test), str(zap)])
